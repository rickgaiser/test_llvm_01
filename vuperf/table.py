#!/usr/bin/env python3
"""Write kernels.S (the micro programs) and kernels.h (their table) for
vuperf.c from the llc outputs <out>/<kernel>.bin and <kernel>.h.

    table.py <out dir> <kernel>...
"""

import os
import sys

out, kernels = sys.argv[1], sys.argv[2:]
blobs = ['.section .vutext, "a"']
inc, rows = [], []
for k in kernels:
    blobs += [".balign 16", f".globl k_{k}", f"k_{k}:", f'.incbin "{out}/{k}.bin"',
              f".globl k_{k}_end", f"k_{k}_end:"]
    inc.append(f'#include "{k}.h"')
    inc.append(f"extern const unsigned char k_{k}[], k_{k}_end[];")
    u = "VU_" + k.upper()
    rows.append(f'  {{"{k}", k_{k}, k_{k}_end, {u}_ENTRY, {u}_SIZE, {u}_N, {u}_ITEM_QW}},')
with open(os.path.join(out, "kernels.S"), "w") as f:
    f.write("\n".join(blobs) + "\n")
with open(os.path.join(out, "kernels.h"), "w") as f:
    f.write("/* generated by table.py */\n" + "\n".join(inc) + "\n")
    f.write("static const struct kernel kernels[] = {\n" + "\n".join(rows) + "\n};\n")
