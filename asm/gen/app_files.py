write('emu_tests.S', EMU_HEAD, [
    emu.cpu8('cpu8'),
    emu.r3000('r3000'),
    emu.tile_decode_mmi('tile_decode'),
    emu.n64_to_ct16('n64_to_ct16', 4, 30, 2),
    emu.guest_loads('guest_loads', 'mmi', 4, 2, 16),
])
