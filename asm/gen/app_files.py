#   FIR 32          20.4 Msmp/s (10.5)  pmaddh on qfsrv-shifted inputs
#   Resample        27.6 Msmp/s (27.3)  scalar, 8 per iteration (4: 26.1)
#   Correlate Q15    539 MMAC/s (264)   pmaddh, qfsrv once per lag % 8
#   Energy f32  VU0 117.8, FPU 112.6 Msmp/s (96.6, 95.9): memory-bound; PREF
